var reYandexAccessToken = regexp.MustCompile(`access_token=([^&]+)`)

func runYandexLoginWindow(baseDir, dataDir string) {
	loginDataDir := filepath.Join(dataDir, "yandex_login_profile")
	_ = os.MkdirAll(loginDataDir, 0755)

	w := webview2.NewWithOptions(webview2.WebViewOptions{
		Debug:     true,
		DataPath:  loginDataDir,
		AutoFocus: true,
		WindowOptions: webview2.WindowOptions{
			Title:  "Вход в Яндекс Музыку",
			Width:  520,
			Height: 680,
			Center: true,
		},
	})
	if w == nil {
		os.Exit(1)
	}
	defer w.Destroy()

	hwnd := uintptr(w.Window())
	setDarkWindowTitleBar(hwnd)

	tokenSaved := false

	// Callback from injected JavaScript
	_ = w.Bind("saveYandexTokenAndClose", func(token string) {
		token = strings.TrimSpace(token)
		if token != "" && !tokenSaved {
			tokenSaved = true
			_ = os.WriteFile(filepath.Join(baseDir, "yandex_token.txt"), []byte(token), 0644)
			_ = os.WriteFile(filepath.Join(dataDir, "yandex_token.txt"), []byte(token), 0644)
			_ = os.WriteFile("yandex_token.txt", []byte(token), 0644)

			// Clean temp login profile
			go func() {
				time.Sleep(300 * time.Millisecond)
				_ = os.RemoveAll(loginDataDir)
			}()

			w.Destroy()
			os.Exit(0)
		}
	})

	// Inject JS to monitor URL for access_token hash parameter
	injectScript := `
		(function() {
			function checkToken() {
				var hash = window.location.hash || '';
				var href = window.location.href || '';
				var full = href + ' ' + hash;
				var m = full.match(/access_token=([^&]+)/);
				if (m && m[1]) {
					try {
						window.saveYandexTokenAndClose(m[1]);
					} catch(e) {}
				}
			}
			setInterval(checkToken, 250);
			window.addEventListener('hashchange', checkToken);
			window.addEventListener('load', checkToken);
		})();
	`
	w.Init(injectScript)

	// Official Yandex Music Mobile OAuth URL
	oauthURL := "https://oauth.yandex.ru/authorize?response_type=token&client_id=23cabbbdc6cd418abb4b9c8a63f73416"
	w.Navigate(oauthURL)

	w.Run()
}

func runYouTubeLoginWindow(baseDir, dataDir string) {
	loginDataDir := filepath.Join(dataDir, "youtube_profile")
	_ = os.MkdirAll(loginDataDir, 0755)

	w := webview2.NewWithOptions(webview2.WebViewOptions{
		Debug:     true,
		DataPath:  loginDataDir,
		AutoFocus: true,
		WindowOptions: webview2.WindowOptions{
			Title:  "Вход в YouTube Music",
			Width:  560,
			Height: 720,
			Center: true,
		},
	})
	if w == nil {
		os.Exit(1)
	}
	defer w.Destroy()

	hwnd := uintptr(w.Window())
	setDarkWindowTitleBar(hwnd)

	cookiesSaved := false

	// Callback from JS to save cookies in Netscape format
	_ = w.Bind("saveYouTubeCookiesAndClose", func(cookieStr, pageUrl string) {
		cookieStr = strings.TrimSpace(cookieStr)
		if cookieStr != "" && !cookiesSaved {
			cookiesSaved = true

			// Parse cookie pairs and build standard Netscape cookies file
			lines := []string{"# Netscape HTTP Cookie File", "# https://curl.haxx.se/rfc/cookie_spec.html", "# This file was generated by FreeToPlayer"}
			pairs := strings.Split(cookieStr, ";")
			now := time.Now().Add(365 * 24 * time.Hour).Unix()

			for _, p := range pairs {
				p = strings.TrimSpace(p)
				if p == "" || !strings.Contains(p, "=") {
					continue
				}
				kv := strings.SplitN(p, "=", 2)
				name := strings.TrimSpace(kv[0])
				val := strings.TrimSpace(kv[1])
				// Domain, include_subdomains, path, secure, expiry, name, value
				line := fmt.Sprintf(".youtube.com\tTRUE\t/\tTRUE\t%d\t%s\t%s", now, name, val)
				lines = append(lines, line)
			}

			netscapeContent := strings.Join(lines, "\n") + "\n"
			_ = os.WriteFile(filepath.Join(baseDir, "youtube_cookies.txt"), []byte(netscapeContent), 0644)
			_ = os.WriteFile(filepath.Join(dataDir, "youtube_cookies.txt"), []byte(netscapeContent), 0644)
			_ = os.WriteFile("youtube_cookies.txt", []byte(netscapeContent), 0644)

			w.Destroy()
			os.Exit(0)
		}
	})

	// Inject JS to detect successful YouTube Music login
	injectScript := `
		(function() {
			function checkLogin() {
				var href = window.location.href || '';
				var cookies = document.cookie || '';
				// Check if reached YouTube Music with auth session cookies
				if (href.includes('music.youtube.com') || href.includes('youtube.com')) {
					if (cookies.includes('SAPISID') || cookies.includes('SSID') || cookies.includes('LOGIN_INFO') || cookies.includes('__Secure-')) {
						try {
							window.saveYouTubeCookiesAndClose(cookies, href);
						} catch(e) {}
					}
				}
			}
			setInterval(checkLogin, 500);
			window.addEventListener('load', checkLogin);
		})();
	`
	w.Init(injectScript)

	loginURL := "https://accounts.google.com/ServiceLogin?service=youtube&continue=https%3A%2F%2Fmusic.youtube.com%2F"
	w.Navigate(loginURL)

	w.Run()
}

// Fetch Yandex account status using token
func getYandexAccountInfo(token string) (map[string]interface{}, error) {
	token = strings.TrimSpace(token)
	if token == "" {
		return map[string]interface{}{"isAuthorized": false}, nil
	}

	req, err := http.NewRequest("GET", "https://api.music.yandex.net/account/status", nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("Authorization", "OAuth "+token)
	req.Header.Set("User-Agent", "YandexMusic/2024.04 (Android 14; Pixel 8)")

	client := &http.Client{Timeout: 5 * time.Second}
	resp, err := client.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return map[string]interface{}{"isAuthorized": false, "error": "Invalid token"}, nil
	}

	var root struct {
		Result struct {
			Account struct {
				DisplayName string `json:"displayName"`
				FullName    string `json:"fullName"`
				Login       string `json:"login"`
				UID         int64  `json:"uid"`
			} `json:"account"`
			Plus struct {
				HasPlus bool `json:"hasPlus"`
			} `json:"plus"`
		} `json:"result"`
	}

	if err := json.NewDecoder(resp.Body).Decode(&root); err != nil {
		return nil, err
	}

	name := root.Result.Account.DisplayName
	if name == "" {
		name = root.Result.Account.FullName
	}
	if name == "" {
		name = root.Result.Account.Login
	}

	return map[string]interface{}{
		"isAuthorized": true,
		"name":         name,
		"login":        root.Result.Account.Login,
		"hasPlus":      root.Result.Plus.HasPlus,
		"uid":          root.Result.Account.UID,
	}, nil
}
